/**
 * Deterministic OHLCV generator for smooth, realistic TradingView candlestick charts
 */
export function generateCandlesForStock(stock: Stock, timeframe: Timeframe): OHLCV[] {
  let count = 40;
  let intervalMs = 60 * 1000 * 5; // 5m default for 1D
  const basePrice = stock.price;
  const isUp = stock.changePercent >= 0;

  switch (timeframe) {
    case '1D':
      count = 48; // every 5-10 mins
      intervalMs = 1000 * 60 * 8;
      break;
    case '5D':
      count = 60;
      intervalMs = 1000 * 60 * 60 * 2;
      break;
    case '1M':
      count = 30;
      intervalMs = 1000 * 60 * 60 * 24;
      break;
    case '3M':
      count = 45;
      intervalMs = 1000 * 60 * 60 * 24 * 2;
      break;
    case '6M':
      count = 60;
      intervalMs = 1000 * 60 * 60 * 24 * 3;
      break;
    case '1Y':
      count = 52;
      intervalMs = 1000 * 60 * 60 * 24 * 7;
      break;
    case '5Y':
    case 'ALL':
      count = 60;
      intervalMs = 1000 * 60 * 60 * 24 * 30;
      break;
  }

  const now = Date.now();
  const startTime = now - count * intervalMs;
  const candles: OHLCV[] = [];

  // Seed with pseudo-random deterministic wave
  const seed = stock.symbol.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const volatility = (stock.beta || 1.0) * 0.015;

  // Starting price based on timeframe trend
  let trendSlope = (stock.changePercent / 100) / count;
  if (timeframe === '1Y' || timeframe === '5Y') {
    trendSlope = 0.004; // general upward growth for major stocks
  }

  let currentPrice = basePrice * (1 - (isUp ? 0.03 : -0.03));
  if (timeframe === '1M' || timeframe === '6M' || timeframe === '1Y') {
    currentPrice = stock.low52 + (stock.price - stock.low52) * 0.4;
  }

  for (let i = 0; i < count; i++) {
    const time = new Date(startTime + i * intervalMs);
    const pseudoRand1 = Math.sin((seed + i * 7.3)) * 0.5 + 0.5;
    const pseudoRand2 = Math.cos((seed * 1.5 + i * 4.1)) * 0.5 + 0.5;

    const drift = (pseudoRand1 - 0.48) * volatility * currentPrice + (trendSlope * currentPrice);
    
    // Last candle matches exactly current price
    let close = i === count - 1 ? stock.price : Math.max(currentPrice * 0.8, currentPrice + drift);
    let open = i === 0 ? currentPrice : candles[i - 1].close;

    if (i === count - 1) {
      open = close - (stock.change / count) * 4;
    }

    const high = Math.max(open, close) + pseudoRand2 * (open * volatility * 0.8);
    const low = Math.min(open, close) - (1 - pseudoRand2) * (open * volatility * 0.8);
    const volume = Math.round((stock.volume / count) * (0.6 + pseudoRand1 * 0.8));

    candles.push({
      time: timeframe === '1D' 
        ? time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
        : time.toLocaleDateString([], { month: 'short', day: 'numeric' }),
      timestamp: time.getTime(),
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentPrice = close;
  }

  return candles;
}
